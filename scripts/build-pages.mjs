import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = process.env.PAGES_OUTPUT_DIR
  ? path.resolve(process.env.PAGES_OUTPUT_DIR)
  : path.join(root, "dist");
const files = [
  "index.html", "cloud-export.html", "styles.css", "ledger.css", "_headers", "_routes.json",
  "app.js", "ledger.js", "runtime-storage.js", "overview-map.js", "route-ui.js",
  "ticket-pdf-preview.js", "site-navigation.js", "travel-content-store.js", "travel-content-view.js",
  "travel-attachment-store.js", "travel-content-editor.js", "travel-phase3-services.js",
  "cloud-client.js", "cloud-migration.js", "cloud-transfer.js"
];

await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
for (const file of files) await cp(path.join(root, file), path.join(output, file));
await cp(path.join(root, "assets"), path.join(output, "assets"), { recursive: true });

// Pages Functions do not support Wrangler's Worker-only Text module rules.
// Generate a JS module beside the Function so Wrangler bundles the template
// into the Function, while the source JSON stays out of the public assets.
const tripTemplate = JSON.parse(await readFile(path.join(root, "trip-data.json"), "utf8"));
const generatedFunctionModule = `// Generated by scripts/build-pages.mjs. Do not edit.\nexport default ${JSON.stringify(tripTemplate, null, 2)};\n`;
await writeFile(path.join(root, "functions", "trip-template.generated.js"), generatedFunctionModule, "utf8");

console.log(`Built Pages assets in ${path.relative(root, output)}; trip-data.json is excluded from static assets and its template is bundled into a Pages Function module.`);
